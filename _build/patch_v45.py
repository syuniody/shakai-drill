# 線がない語句の問題を k→h。問題は消さない（記録キーはそのまま）
import io,re,sys
P=sys.argv[1]; s=io.open(P,encoding="utf-8").read()
DEMOTE={
 "kd1":[10],            # 面積がいちばん小さい島（四国）…本文に線なし
 "kd3":[8,12],          # ロシアは日本の約45倍・一人っ子政策の廃止
 "kd4":[0,1,2,3,4,5,6,7],  # 領土・領海・領空・排他的経済水域・公海…p18の図だけで線なし
 "kd6":[1,3,5],         # 火山200以上・噴火の災害4つ・地熱発電（温泉・地熱発電の問と重複）
 "kd7":[0,1,4,5,6],     # 東北は南北・西南は東西・日本海側/太平洋側・3000m級…線なし
 "kd8":[7,10],          # 雲仙岳の1991年・火砕流の説明
 "kd9":[0,1,2,9],       # 岩盤のずれ・プレート・4つ・富士山の県…線なし
 "kd10":[2,5],          # 船の運行・堤防
 "kd12":[7,15],         # 流域面積の2位3位までの順・流域面積の説明
 "kd13":[12,20],        # 阿武隈川・吉野川…p25で線なし
 "kd14":[12,19,20,21,22],  # 砂浜は日本海側・霞ヶ浦の県・サロマ湖・湖の順位
 "kd19":[0,3,8],        # 地図：有珠山・八ヶ岳・三宅島
 "kd20":[4,5],          # 地図：阿武隈川・阿賀野川
 "kd21":[5],            # 地図：吉野川
 "kd24":[7],            # 地図：サロマ湖
}
m=re.search(r"const LEVEL=\{",s); i=m.end(); j=s.index("};",i); body=s[i:j]
for sid,idx in DEMOTE.items():
    mm=re.search(r'"%s":"([kh]+)"'%sid,body); assert mm,sid
    l=list(mm.group(1))
    for k in idx:
        assert l[k]=="k",(sid,k); l[k]="h"
    body=body[:mm.start(1)]+"".join(l)+body[mm.end(1):]
s=s[:i]+body+s[j:]
s=s.replace("v44 ・ 11/14更新","v45 ・ 11/14更新",1)
io.open(P,"w",encoding="utf-8").write(s)
L=dict(re.findall(r'"(kd\d+)":"([kh]+)"',body))
print("日本の国土（3・4） 基本",sum(v.count("k") for v in L.values()),"発展",sum(v.count("h") for v in L.values()))
