def core(a): return [x for x in re.sub(r"（.*?）", "", a).split("・") if x]

def leaks(chosen):
    """選んだ (答え, 問) の組で、答えがほかの問題文に出ているか"""
    for a, _ in chosen:
        for a2, q2 in chosen:
            if a != a2 and any(c in q2 for c in core(a)):
                return True
    return False

def excl_ok(answers):
    return all(len(g & set(answers)) <= 1 for g in EXCL)

def build(seed=20261115):
    rnd = random.Random(seed)
    used, qused = Counter(), Counter()
    tests = []
    for t in range(N):
        best = None
        for _try in range(3000):
            chosen = []
            for sec in range(3):
                items = [p for p in POOL if p[0] == sec]
                # 出た回数が少ないものほど選ばれやすい（ゆらぎ入り）
                key = lambda p: used[p[1]] + rnd.random() * (1.5 + _try / 300)
                w = sorted([p for p in items if p[2]], key=key)[:WEAK_SLOTS[sec]]
                o = sorted([p for p in items if not p[2]], key=key)[:SLOTS[sec] - len(w)]
                chosen += sorted(w + o, key=POOL.index)
            if not excl_ok([p[1] for p in chosen]):
                continue
            for _ in range(40):
                pairs = []
                for p in chosen:
                    ix = sorted(range(len(p[3])), key=lambda i: qused[(p[1], i)] + rnd.random() * 1.2)
                    pairs.append((p[1], p[3][ix[0]]))
                if not leaks(pairs):
                    best = (chosen, pairs); break
            if best: break
        if not best:
            raise SystemExit(f"第{t+1}回が組めない")
        chosen, pairs = best
        for p, (a, q) in zip(chosen, pairs):
            used[a] += 1; qused[(a, p[3].index(q))] += 1
        tests.append([(p[0], a, q) for p, (a, q) in zip(chosen, pairs)])
    return tests, used

