    for m in RE.finditer(q):
        w = m.group(0)
        if len(w) == 1 and w not in ONE: continue
        out.append(E(q[last:m.start()]))
        out.append(E(w) if w in ans else f"<ruby>{E(w)}<rt>{RUBY[w]}</rt></ruby>")
        last = m.end()
    out.append(E(q[last:]))
    return "".join(out)

